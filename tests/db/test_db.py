import sys, json
sys.path.insert(0, __import__("os").path.dirname(__file__))
from harness import *

start()
try:
    a, b, c = user("ana", "ana@x.com"), user("beto"), user("cris")

    print("Cuentas, ligas y planes (etapa 1-2)")
    check("crear liga", val("ana", "select create_league('Liga Reforma')") == "liga-reforma")
    check("rol inventado se rechaza", fails("ana", "select set_roles(array['admin'])", "check"))
    check("nadie se da Pro", fails("beto", "insert into subscriptions (subject_type,subject_id,plan_id) values ('team','x/y','team-pro')"))
    check("equipo nuevo", "los-halcones" in val("beto", "select create_team('Los Halcones', 7)"))
    check("tope de equipos del plan gratis", fails("beto", "select create_team('Otro', 7)", "máximo"))
    check("solo el admin agrega jugadores", fails("cris", "select add_player('los-halcones','principal','Intruso','1','')", "sin permiso"))

    print("Invitaciones, vinculación y Pro por contrato (etapa 3)")
    check("la liga crea invitación", re.fullmatch(r"[0-9A-F]{4}-[0-9A-F]{4}-[0-9A-F]{4}", code := val("ana", "select create_invite('liga-reforma','Temporada otoño', 5, 30)")) is not None, code)
    check("quien no administra la liga no crea invitaciones", fails("beto", "select create_invite('liga-reforma','x')", "sin permiso"))
    check("beto no ve las invitaciones de ana", val("beto", "select count(*) from league_invites") == "0")
    check("código malo no da pista", json.loads(val("beto", "select request_link('AAAA-BBBB-CCCC','los-halcones','principal')"))["error"] == "invalid")
    check("solo el delegado del equipo vincula", fails("cris", f"select request_link('{code}','los-halcones','principal')", "sin permiso"))
    r = json.loads(val("beto", f"select request_link(lower('{code}'),'los-halcones','principal')"))
    check("solicitud con código válido (acepta minúsculas)", r.get("ok") is True, r)
    check("no se duplica la solicitud", json.loads(val("beto", f"select request_link('{code}','los-halcones','principal')")).get("error") == "duplicate")
    check("sin contrato, el equipo sigue gratis", json.loads(val("beto", "select entitlement('team','los-halcones/principal')"))["name"] == "Equipo Gratis")
    lt = val("ana", "select id from league_teams limit 1")
    check("beto no puede aprobar su propia solicitud", fails("beto", f"select decide_link('liga-reforma','{lt}',true)", "sin permiso"))
    r = json.loads(val("ana", f"select decide_link('liga-reforma','{lt}',true)"))
    check("aprobado sin contrato: vinculado pero sin Pro", r == {"ok": True, "pro": False}, r)
    q("srv", "insert into league_contracts (league_id, pro_slots) values ('liga-reforma', 1)")
    check("sin cupo asignado no hay Pro aunque haya contrato", json.loads(val("beto", "select entitlement('team','los-halcones/principal')"))["name"] == "Equipo Gratis")
    check("la liga asigna Pro dentro del cupo", val("ana", f"select set_team_pro('liga-reforma','{lt}',true)") == "")
    e = json.loads(val("beto", "select entitlement('team','los-halcones/principal')"))
    check("el equipo recibe Pro de la liga", e["name"] == "Equipo Pro" and e["source"] == "league" and e["league_id"] == "liga-reforma", e)
    check("beto no ve contratos ajenos", val("beto", "select count(*) from league_contracts") == "0")
    check("contrato visible para la liga", json.loads(val("ana", "select league_contract('liga-reforma')"))["used"] == 1)
    # segundo equipo: no cabe en el cupo
    user("dana"); q("dana", "select create_team('Tigres', 7)")
    code2 = val("ana", "select create_invite('liga-reforma','otro')")
    check("segundo equipo solicita", json.loads(val("dana", f"select request_link('{code2}','tigres','principal')")).get("ok"))
    lt2 = val("ana", "select id from league_teams where club_id='tigres'")
    check("se aprueba sin Pro cuando el cupo está lleno", json.loads(val("ana", f"select decide_link('liga-reforma','{lt2}',true)")) == {"ok": True, "pro": False})
    check("no se excede el cupo manualmente", fails("ana", f"select set_team_pro('liga-reforma','{lt2}',true)", "espacios"))
    # vencimiento
    q("srv", "update league_contracts set ends_at = now() - interval '1 day'")
    check("contrato vencido retira solo el Pro de liga", json.loads(val("beto", "select entitlement('team','los-halcones/principal')"))["name"] == "Equipo Gratis")
    check("contrato vencido: equipo y jugadores intactos", val("srv", "select count(*) from team_docs where club_id='los-halcones'") == "1")
    q("srv", "update league_contracts set ends_at = null")
    # Pro propio se conserva
    q("srv", "insert into subscriptions (subject_type,subject_id,plan_id,source) values ('team','los-halcones/principal','team-pro','manual')")
    q("srv", "update league_contracts set status='canceled'")
    e = json.loads(val("beto", "select entitlement('team','los-halcones/principal')"))
    check("liga cancelada: conserva su Pro propio", e["name"] == "Equipo Pro" and e["source"] == "manual", e)
    q("srv", "update league_contracts set status='active'")
    e = json.loads(val("beto", "select entitlement('team','los-halcones/principal')"))
    check("con ambos, gana la suscripción propia", e["source"] == "manual", e)
    # desvincular
    check("un tercero no desvincula", fails("cris", f"select unlink_team('{lt}')", "sin permiso"))
    check("el delegado se desvincula", val("beto", f"select unlink_team('{lt}')") == "")
    check("historial conservado (status left)", val("srv", f"select status from league_teams where id='{lt}'") == "left")
    q("srv", "delete from subscriptions")
    check("desvinculado: ya no hay Pro de liga", json.loads(val("beto", "select entitlement('team','los-halcones/principal')"))["name"] == "Equipo Gratis")
    check("puede volver a solicitar", json.loads(val("beto", f"select request_link('{code}','los-halcones','principal')")).get("ok"))
    # invitación: usos, revocación, intentos
    check("revocar invitación", val("ana", f"select revoke_invite('liga-reforma','{code2}')") == "")
    check("invitación revocada no sirve", json.loads(val("dana", f"select request_link('{code2}','tigres','principal')")).get("error") in ("invalid", "duplicate"))
    for i in range(8): q("beto", "select request_link('ZZZZ-ZZZZ-ZZZZ','los-halcones','principal')")
    check("bloqueo tras muchos intentos fallidos", json.loads(val("beto", f"select request_link('{code}','los-halcones','principal')")).get("error") == "throttled")
    check("bitácora registra acciones", int(val("ana", "select count(*) from audit_log where league_id='liga-reforma'")) >= 5)
    check("beto no lee la bitácora", val("beto", "select count(*) from audit_log") == "0")
    check("nadie edita la bitácora", fails("ana", "delete from audit_log"))
    check("funciones internas no son llamables", fails("ana", "select league_pro_teams()") and fails("ana", "select log_action('liga-reforma','x')"))
    check("beto ve los vínculos de su equipo", int(val("beto", "select count(*) from team_links('los-halcones','principal')")) >= 2)
    check("cris no ve vínculos ajenos", val("cris", "select count(*) from team_links('los-halcones','principal')") == "0")
finally:
    ok = summary(); stop(); sys.exit(0 if ok else 1)
